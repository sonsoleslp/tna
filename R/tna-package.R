"_PACKAGE"

#' Example Data on Student Engagement
#'
#' Students' engagement states (Active / Average / Disengaged)
#' throughout a whole study program. The data was generated synthetically
#' based on the article "The longitudinal association between engagement and
#' achievement varies by time, students' profiles, and achievement state:
#' A full program study"
#'
#' @family datasets
#' @source \doi{10.1016/j.compedu.2023.104787}
#' @format A `stslist` object (sequence data) with 1000 sequences (rows) and
#'   25 time points (columns), over the states `"Active"`, `"Average"`, and
#'   `"Disengaged"`.
"engagement"

#' Example Mixture Markov Model Object for the `engagement` Data
#'
#' A `tna_mmm` object structurally equivalent to a fitted seqHMM
#' mixture Markov model, used by the package's examples for
#' `group_model()` and `mmm_stats()`. Generated deterministically by
#' [random_tna_mmm()] with engagement-flavored state labels and
#' three clusters; carries no foreign class references so it is safe
#' to bundle.
#'
#' Re-generate via `data-raw/engagement_mmm.R` whenever the simulator
#' changes.
#'
#' @family datasets
#' @source Generated by `data-raw/engagement_mmm.R` using
#' [random_tna_mmm()].
#' @format A `tna_mmm` object containing three clusters over the
#'   states `"Engaged"`, `"Moderate"`, `"Disengaged"`, for 1000
#'   sequences.
"engagement_mmm"

#' Example Wide Data on Group Regulation
#'
#' Students' regulation during collaborative learning. Students' interactions
#' were coded as:  "adapt", "cohesion", "consensus", "coregulate", "discuss",
#' "emotion", "monitor", "plan", "synthesis"
#'
#' @family datasets
#' @source The data was generated synthetically.
#' @format A `data.frame` with 2000 sequences (rows) and 26 time points
#'   (columns `T1` to `T26`). Shorter sequences end in missing values. The
#'   first 1000 rows are the sequences of high achievers and the last 1000
#'   rows those of low achievers (see `group_regulation_long`).
"group_regulation"

#' Example Long Data on Group Regulation
#'
#' Students' regulation during collaborative learning. This is the same dataset
#' as `group_regulation` but in long format. In addition to students'
#' actions (`Action`), it contains the student identifier (`Actor`),
#' timestamp (`Time`), `Course` name, and collaboration `Group`. It
#' also includes a column (`Achiever`) indicating whether the student
#' is a high or low achiever.
#'
#' @family datasets
#' @source The data was generated synthetically from `group_regulation`.
#' @format A tibble with 27533 rows (one per action) and 6 columns:
#'   `Actor` (`integer`), `Achiever` (`"High"` or `"Low"`), `Group`
#'   (`numeric`), `Course` (`character`), `Time` (`POSIXct`), and `Action`
#'   (`character`).
"group_regulation_long"
